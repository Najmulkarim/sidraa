'use client';

import { useRouter } from 'next/navigation';
import { useEffect, useState } from 'react';
import { getBrowserClient } from '@/lib/supabase/browser';

type Factor = { id: string; friendly_name?: string; status: string; created_at: string };

/**
 * Two-factor enrolment with an authenticator app (TOTP). Once a factor is
 * verified, the database's is_admin() requires a two-factor session.
 */
export function MfaSetup() {
  const router = useRouter();
  const [factors, setFactors] = useState<Factor[] | null>(null);
  const [enrol, setEnrol] = useState<{ id: string; qr: string; secret: string } | null>(null);
  const [code, setCode] = useState('');
  const [msg, setMsg] = useState<string | null>(null);
  const [busy, setBusy] = useState(false);

  async function load() {
    const { data } = await getBrowserClient().auth.mfa.listFactors();
    setFactors((data?.totp ?? []) as Factor[]);
  }
  useEffect(() => {
    void load();
  }, []);

  async function start() {
    setBusy(true);
    setMsg(null);
    const supabase = getBrowserClient();
    // Clear any half-finished enrolment first.
    const { data: list } = await supabase.auth.mfa.listFactors();
    for (const f of list?.all ?? []) if (f.status === 'unverified') await supabase.auth.mfa.unenroll({ factorId: f.id });
    const { data, error } = await supabase.auth.mfa.enroll({ factorType: 'totp', friendlyName: `Authenticator ${new Date().toISOString().slice(0, 10)}` });
    setBusy(false);
    if (error || !data) {
      setMsg(error?.message ?? 'Could not start setup.');
      return;
    }
    setEnrol({ id: data.id, qr: data.totp.qr_code, secret: data.totp.secret });
  }

  async function verify() {
    if (!enrol || !/^\d{6}$/.test(code)) {
      setMsg('Enter the 6-digit code shown in the app.');
      return;
    }
    setBusy(true);
    const { error } = await getBrowserClient().auth.mfa.challengeAndVerify({ factorId: enrol.id, code });
    setBusy(false);
    if (error) {
      setMsg('That code did not work. Try the newest code.');
      return;
    }
    setEnrol(null);
    setCode('');
    setMsg('Two-factor sign-in is on. You will be asked for a code each time you sign in.');
    await load();
    router.refresh();
  }

  async function remove(id: string) {
    if (!window.confirm('Turn off two-factor sign-in for this account?')) return;
    const { error } = await getBrowserClient().auth.mfa.unenroll({ factorId: id });
    setMsg(error ? error.message : 'Removed.');
    await load();
    router.refresh();
  }

  const verified = (factors ?? []).filter((f) => f.status === 'verified');

  return (
    <section className="card space-y-4 p-5">
      <div>
        <h2 className="font-semibold">Two-factor sign-in</h2>
        <p className="text-sm text-muted">Protects the admin panel even if your password leaks. Use Google Authenticator, Microsoft Authenticator, 1Password or similar.</p>
      </div>
      {factors === null ? (
        <p className="text-sm text-muted">Loading…</p>
      ) : verified.length > 0 ? (
        <ul className="space-y-2 text-sm">
          {verified.map((f) => (
            <li key={f.id} className="flex items-center justify-between rounded-xl border border-line p-3">
              <span><span className="badge badge-ok mr-2">On</span>{f.friendly_name ?? 'Authenticator app'}</span>
              <button type="button" className="text-sm text-bad underline" onClick={() => remove(f.id)}>Turn off</button>
            </li>
          ))}
        </ul>
      ) : enrol ? (
        <div className="grid gap-4 sm:grid-cols-[auto_1fr] sm:items-start">
          {/* The QR code is an SVG data URL generated by Supabase Auth. */}
          <img src={enrol.qr} alt="QR code for your authenticator app" className="h-44 w-44 rounded-xl border border-line bg-white p-2" />
          <div className="space-y-3">
            <p className="text-sm">1. Scan the code with your authenticator app (or type this key: <code className="break-all font-mono text-xs">{enrol.secret}</code>).</p>
            <p className="text-sm">2. Enter the 6-digit code it shows:</p>
            <div className="flex gap-2">
              <input inputMode="numeric" maxLength={6} value={code} onChange={(e) => setCode(e.target.value.replace(/\D/g, ''))} className="input w-36 text-center font-mono tracking-[0.3em]" aria-label="6-digit code" />
              <button type="button" className="btn btn-primary" disabled={busy} onClick={verify}>Turn on</button>
            </div>
          </div>
        </div>
      ) : (
        <button type="button" className="btn btn-primary" disabled={busy} onClick={start}>Set up two-factor sign-in</button>
      )}
      {msg && <p className="text-sm text-muted" role="status">{msg}</p>}
    </section>
  );
}
